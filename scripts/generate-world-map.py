#!/usr/bin/env python3
"""Turn the GSHHS coastline into the SVG outline the panel draws under the map.

Run this once on a development machine, commit the result. The panel never runs
it, and the data package it reads is not installed on the appliance:

    sudo apt-get install --no-install-recommends python-mpltoolkits.basemap-data
    python3 scripts/generate-world-map.py

Why GSHHS out of a Debian package rather than a map tile service: the device has
to work with no route to the internet, and the panel's CSP blocks every external
host anyway. An outline is also the only geographic detail worth having here -
country level is all the IP database resolves, so borders would suggest an
accuracy the data does not have.

The "c" (crude) resolution is deliberate. At the size this renders, roughly a
thousand pixels across, "l" adds 7x the points and nothing an eye can see.
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

DATA_DIR = Path("/usr/share/basemap/data")
OUT_PATH = Path(__file__).resolve().parent.parent / "frontend/src/app/shared/world-outline.ts"

# Plate carree, so the component can place a marker with the same two lines of
# arithmetic the outline was built with.
WIDTH = 1000
# Cut off below the southern tip of South America and above northern Greenland.
# Antarctica is a third of the vertical space for a landmass that never sources
# an alert, and dropping it turns a squat map into a usable 2.5:1 banner.
LAT_MAX = 84.0
LAT_MIN = -58.0
HEIGHT = round(WIDTH * (LAT_MAX - LAT_MIN) / 360)

# Minimum spacing between consecutive points, in degrees. Radial distance, not
# Douglas-Peucker: on a coastline sampled this coarsely the two agree, and this
# one fits in three lines.
EPSILON = 0.35

# Islands smaller than this (square kilometres, from the GSHHS metadata) come
# out as a single pixel of noise.
MIN_AREA_KM2 = 900.0


def project(lon: float, lat: float) -> tuple[float, float]:
    x = (lon + 180.0) * WIDTH / 360.0
    y = (LAT_MAX - lat) * HEIGHT / (LAT_MAX - LAT_MIN)
    return x, y


def load_polygons() -> list[list[tuple[float, float]]]:
    """Read gshhs_c.dat through its metadata index.

    Format: the .dat is nothing but little-endian float32 lon/lat pairs, and
    each line of the meta file says where one polygon starts and how long it is:
        level area npoints south north byte_offset byte_length id

    Level 1 is a coastline; 2 is a lake, 3 an island inside one. Only level 1 is
    kept - a lake drawn in the same fill as the land shows up as a scribble in
    the middle of a continent, and cutting it out would need even-odd fill rules
    for no gain at this size.
    """
    dat = DATA_DIR / "gshhs_c.dat"
    meta = DATA_DIR / "gshhsmeta_c.dat"
    if not dat.is_file():
        sys.exit(
            f"{dat} is missing. Install it with:\n"
            "  sudo apt-get install --no-install-recommends python-mpltoolkits.basemap-data"
        )

    raw = dat.read_bytes()
    out: list[list[tuple[float, float]]] = []
    for line in meta.read_text().splitlines():
        fields = line.split()
        if len(fields) < 7:
            continue
        if fields[0] != "1":
            continue
        area = float(fields[1])
        npoints = int(fields[2])
        south, north = float(fields[3]), float(fields[4])
        offset, length = int(fields[5]), int(fields[6])

        if area < MIN_AREA_KM2:
            continue
        if north < LAT_MIN or south > LAT_MAX:
            continue

        flat = struct.unpack(f"<{npoints * 2}f", raw[offset:offset + length])
        out.append([(flat[i], flat[i + 1]) for i in range(0, len(flat), 2)])
    return out


def simplify(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
    kept = [points[0]]
    for point in points[1:]:
        if abs(point[0] - kept[-1][0]) + abs(point[1] - kept[-1][1]) > EPSILON:
            kept.append(point)
    return kept


def to_path(points: list[tuple[float, float]]) -> str:
    coords = [project(lon, lat) for lon, lat in points]
    body = "L".join(f"{x:.1f} {y:.1f}" for x, y in coords)
    return f"M{body}Z"


def main() -> None:
    polygons = [simplify(p) for p in load_polygons()]
    paths = [to_path(p) for p in polygons if len(p) >= 4]
    literals = ",\n  ".join(f"'{d}'" for d in paths)

    OUT_PATH.write_text(
        "// Generated by scripts/generate-world-map.py - do not edit by hand.\n"
        "// Source: GSHHS crude coastline, Debian package python-mpltoolkits.basemap-data\n"
        "// (public domain, Wessel & Smith).\n"
        "\n"
        "/** Plate carree box the paths below are drawn in. Anything placed on the\n"
        " *  map has to be projected with these same four numbers. */\n"
        "export const WORLD_VIEW = {\n"
        f"  width: {WIDTH},\n"
        f"  height: {HEIGHT},\n"
        f"  latMax: {LAT_MAX},\n"
        f"  latMin: {LAT_MIN},\n"
        "} as const;\n"
        "\n"
        "/** One closed path per landmass, already projected into WORLD_VIEW. */\n"
        "export const WORLD_PATHS: readonly string[] = [\n"
        f"  {literals},\n"
        "];\n",
        encoding="utf-8",
    )
    size = OUT_PATH.stat().st_size
    print(f"{OUT_PATH}: {len(paths)} paths, {size // 1024} KiB")


if __name__ == "__main__":
    main()

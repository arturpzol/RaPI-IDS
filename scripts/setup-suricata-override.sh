#!/usr/bin/env bash
# Wire the panel override file into the engine configuration so the log
# directory can be changed from the GUI. Idempotent - safe to run repeatedly.
#
# What it does:
#   1. creates /etc/suricata/rapi-overrides.yaml (owned by the panel user),
#   2. appends an "include: ..." line at the end of suricata.yaml - values from
#      a later include win, so the panel can override default-log-dir,
#   3. turns the WebSocket parser off (see below),
#   4. points HOME_NET at the networks this machine is on (see below),
#   5. verifies the config (suricata -T) and rolls back if anything breaks.
#
# The packaged suricata.yaml is edited in exactly three places, all marked; a
# backup sits next to it with the .rapi-bak suffix.
#
# Why step 3 is an edit and not an override: an include replaces a whole
# top-level key rather than merging into it. Putting "app-layer:" in the
# override file would wipe out all 28 protocol parsers and leave only the one
# we named - silently losing HTTP, TLS, DNS and the rest. Only scalar
# top-level keys (default-log-dir) are safe to set from the override.
set -euo pipefail

YAML="${RAPI_SURICATA_YAML:-/etc/suricata/suricata.yaml}"
OVERRIDE="${RAPI_SURICATA_OVERRIDE:-/etc/suricata/rapi-overrides.yaml}"
# The account the panel runs as, which is who writes the override file. Under
# sudo that is the caller. The first boot runs this as root from a unit, where
# systemd leaves USER empty and there is no SUDO_USER, so it names the account
# in RAPI_PANEL_USER. Without that, `chown :` succeeded, changed nothing, and
# every flashed card came up with a file the panel could not write.
PANEL_USER="${RAPI_PANEL_USER:-${SUDO_USER:-${USER:-}}}"
if [[ -z "$PANEL_USER" || "$PANEL_USER" == root ]]; then
  echo "Cannot tell which account the panel runs as. Run this with sudo from" \
       "that account, or set RAPI_PANEL_USER." >&2
  exit 1
fi

if [[ ! -f "$YAML" ]]; then
  echo "Cannot find $YAML - is the engine installed?" >&2
  exit 1
fi

# Snapshot before any edit, refreshed every run. This used to be a "cp -n", which
# meant the backup stayed at whatever version was installed the very first time -
# after the 7.0.10 -> 8.0.6 upgrade a rollback would have restored a Suricata 7
# config onto a Suricata 8 engine. The rollback target has to be the state this
# run started from; dpkg keeps the pristine packaged file as .dpkg-old anyway.
sudo cp "$YAML" "${YAML}.rapi-bak"

echo "==> Override file: $OVERRIDE (owner: $PANEL_USER)"
if [[ ! -f "$OVERRIDE" ]]; then
  sudo tee "$OVERRIDE" >/dev/null <<EOF
%YAML 1.1
---
# Generated by RaPi IDS Panel - do not edit by hand.
EOF
fi
sudo chown "$PANEL_USER":"$PANEL_USER" "$OVERRIDE"
sudo chmod 0644 "$OVERRIDE"

if grep -qE "^\s*include:\s*${OVERRIDE}\s*$" "$YAML"; then
  echo "==> include already wired - nothing to change"
else
  # The old one-line form, because the helper that keeps them in an array is
  # not installed yet at this point. It is rewritten into the array further
  # down, when rapi-outputs runs and calls rapi-include.
  echo "==> Appending include to $YAML (backup: ${YAML}.rapi-bak)"
  printf '\n# --- RaPi IDS Panel: overrides from the panel (must stay last) ---\ninclude: %s\n' \
    "$OVERRIDE" | sudo tee -a "$YAML" >/dev/null

  echo "==> Verifying the engine configuration"
  if ! sudo suricata -T -c "$YAML" >/dev/null 2>&1; then
    echo "Configuration fails the test - rolling back." >&2
    sudo cp "${YAML}.rapi-bak" "$YAML"
    exit 1
  fi
fi

# The panel talks to the browser over a WebSocket, so with this parser on the
# engine logs every frame of the panel's own traffic - roughly 200 MB an hour of
# eve.json describing the IDS watching itself. The Pi sees only its own traffic
# anyway, so there is no third-party WebSocket here worth inspecting. Re-enable
# it by hand if the Pi is ever fed a mirrored port.
MARKER="# RaPi IDS Panel: off, the panel's own WebSocket floods eve.json"
if grep -qF "$MARKER" "$YAML"; then
  echo "==> WebSocket parser already switched off"
else
  echo "==> Switching the WebSocket parser off in $YAML"
  sudo awk -v marker="$MARKER" '
    # Only the websocket entry under app-layer.protocols - a four-space key.
    /^    websocket:$/ { inblock = 1; print; next }
    # Any key at the same or shallower depth ends the block.
    inblock && /^ {0,4}[a-z0-9_-]+:/ { inblock = 0 }
    inblock && /^ *#?enabled:/ && !done {
      print "      enabled: no   " marker
      done = 1
      next
    }
    { print }
  ' "$YAML" > /tmp/rapi-suricata-yaml.$$ && sudo cp /tmp/rapi-suricata-yaml.$$ "$YAML"
  rm -f /tmp/rapi-suricata-yaml.$$

  if ! grep -qF "$MARKER" "$YAML"; then
    echo "Could not find the websocket entry - leaving the config alone." >&2
    sudo cp "${YAML}.rapi-bak" "$YAML"
  elif ! sudo suricata -T -c "$YAML" >/dev/null 2>&1; then
    echo "Configuration fails the test - rolling back." >&2
    sudo cp "${YAML}.rapi-bak" "$YAML"
    exit 1
  fi
fi

# The packaged HOME_NET covers the RFC1918 ranges and nothing else. This
# machine is not in any of them, which quietly breaks detection: most of ET Open
# is directional ($EXTERNAL_NET -> $HOME_NET), and a sensor sitting outside
# HOME_NET can never satisfy that. The rules load, count as active and never
# fire. So the value has to follow the machine instead of the package default.
#
# Why an edit and not the override file: address-groups lives under the
# top-level "vars" key, and an include replaces a whole top-level key. Setting
# "vars:" from the override would take EXTERNAL_NET, HTTP_SERVERS and every port
# group down with it - the same trap as app-layer above.
#
# Resolution order: RAPI_HOME_NET, then the remembered value, then the subnets
# this machine is connected to. The choice is remembered outside suricata.yaml
# because a package upgrade replaces that file, and re-running this script must
# not silently narrow HOME_NET back to whatever a single interface happens to
# have at the time.
HOME_NET_STATE="${RAPI_HOME_NET_STATE:-/etc/suricata/rapi-home-net}"

detect_home_net() {
  local nets
  nets="$(ip -4 -o route show scope link 2>/dev/null \
    | awk '$1 ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+\// && $1 !~ /^169\.254\./ {print $1}' \
    | sort -u | paste -sd,)"
  # An if, not `[[ ]] && printf`: with no IPv4 link route (no cable yet, an
  # IPv6-only network) that form returns 1, and under set -e the assignment
  # below took the whole script down before its own "leave HOME_NET alone"
  # branch, skipping the output and tuning helpers after it. On the first boot
  # that was silent, and those two were then never installed.
  if [[ -n "$nets" ]]; then printf '[%s]' "$nets"; fi
}

if [[ -n "${RAPI_HOME_NET:-}" ]]; then
  HOME_NET="$RAPI_HOME_NET"
elif [[ -s "$HOME_NET_STATE" ]]; then
  HOME_NET="$(cat "$HOME_NET_STATE")"
else
  HOME_NET="$(detect_home_net)"
fi

HN_MARKER="# RaPi IDS Panel: HOME_NET follows this machine"
if [[ -z "$HOME_NET" ]]; then
  echo "Could not work out HOME_NET - leaving the packaged value alone." >&2
elif grep -qF "HOME_NET: \"$HOME_NET\"   $HN_MARKER" "$YAML"; then
  echo "==> HOME_NET already set to $HOME_NET"
  printf '%s\n' "$HOME_NET" | sudo tee "$HOME_NET_STATE" >/dev/null
else
  echo "==> Setting HOME_NET to $HOME_NET in $YAML"
  sudo awk -v val="$HOME_NET" -v marker="$HN_MARKER" '
    # The first uncommented HOME_NET wins; the rest of the block is examples.
    !done && /^[[:space:]]*HOME_NET:/ && $0 !~ /^[[:space:]]*#/ {
      print "    HOME_NET: \"" val "\"   " marker
      done = 1
      next
    }
    { print }
  ' "$YAML" > /tmp/rapi-suricata-yaml.$$ && sudo cp /tmp/rapi-suricata-yaml.$$ "$YAML"
  rm -f /tmp/rapi-suricata-yaml.$$

  if ! grep -qF "$HN_MARKER" "$YAML"; then
    echo "Could not find the HOME_NET entry - leaving the config alone." >&2
    sudo cp "${YAML}.rapi-bak" "$YAML"
  elif ! sudo suricata -T -c "$YAML" >/dev/null 2>&1; then
    echo "Configuration fails the test - rolling back." >&2
    sudo cp "${YAML}.rapi-bak" "$YAML"
    exit 1
  else
    printf '%s\n' "$HOME_NET" | sudo tee "$HOME_NET_STATE" >/dev/null
  fi
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
echo "==> Log rotation helper (the panel calls it over sudo after a move)"
sudo install -m 0755 -o root -g root "$ROOT/deploy/rapi-log-dir" \
  /usr/local/sbin/rapi-log-dir

echo "==> Capture helpers (the panel calls them over sudo from the topology wizard)"
for helper in rapi-capture-apply rapi-capture-iface rapi-capture-probe rapi-bridge \
              rapi-ips-mode rapi-inline; do
  sudo install -m 0755 -o root -g root "$ROOT/deploy/$helper" "/usr/local/sbin/$helper"
done

# Not in the loop above and not in sudoers: the panel never calls this one. What
# the engine writes to disk is decided once, here.
echo "==> What the engine writes to disk (fast.log and stats.log off)"
sudo install -m 0755 -o root -g root "$ROOT/deploy/rapi-include" /usr/local/sbin/rapi-include
sudo install -m 0755 -o root -g root "$ROOT/deploy/rapi-outputs" /usr/local/sbin/rapi-outputs
sudo /usr/local/sbin/rapi-outputs

echo "==> Engine tuning (stream bypass, matcher)"
sudo install -m 0755 -o root -g root "$ROOT/deploy/rapi-tuning" /usr/local/sbin/rapi-tuning
sudo /usr/local/sbin/rapi-tuning

# Set up rotation for the directory the engine uses right now.
CURRENT_DIR="$(suricata --dump-config -c "$YAML" 2>/dev/null \
  | sed -n 's/^default-log-dir = //p' | tail -1)"
if [[ -n "$CURRENT_DIR" && -d "$CURRENT_DIR" ]]; then
  sudo /usr/local/sbin/rapi-log-dir "${CURRENT_DIR%/}"
fi

echo
echo "Done. The log directory can now be changed in the panel (IDS -> Logi)."

def connect() -> sqlite3.Connection:
    """One connection per thread (sqlite3 dislikes sharing across threads)."""
    conn = getattr(_local, "conn", None)
    if conn is None:
        config.DATA_DIR.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(config.DB_PATH, timeout=30.0)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA journal_mode=WAL")
        conn.execute("PRAGMA synchronous=NORMAL")
        conn.execute("PRAGMA busy_timeout=30000")
        _local.conn = conn
    return conn


def init() -> None:
    conn = connect()
    with _write_lock:
        conn.executescript(SCHEMA)
        _migrate(conn)
        conn.commit()


def _migrate(conn: sqlite3.Connection) -> None:
    """Columns added after a release, for databases that already exist.

    CREATE TABLE IF NOT EXISTS does nothing to a table that is already there, so
    a new column has to be added by hand or the panel comes up against a schema
    one version behind and fails on the first query.
    """
    columns = {row["name"] for row in conn.execute("PRAGMA table_info(alerts)")}
    if columns and "src_cc" not in columns:
        conn.execute("ALTER TABLE alerts ADD COLUMN src_cc TEXT")
    if columns and "et_severity" not in columns:
        conn.execute("ALTER TABLE alerts ADD COLUMN et_severity TEXT")
    if columns and "action" not in columns:
        conn.execute("ALTER TABLE alerts ADD COLUMN action TEXT")
    _epoch_timestamps(conn)
    # After the ALTERs, and unconditional: a fresh database gets the columns from
    # SCHEMA above, so this is the one place both paths meet.
    conn.execute("CREATE INDEX IF NOT EXISTS idx_alerts_src_cc ON alerts(src_cc)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_alerts_et_sev ON alerts(et_severity)")
    _label_unnamed(conn)
    _drop_stored_duplicate_anomalies(conn)


def _epoch_timestamps(conn: sqlite3.Connection) -> None:
    """Rewrite ISO timestamps as Unix seconds, once, by rebuilding the table.

    Updating in place does not work and fails silently, which cost this database
    once already. The old column was declared TEXT, and in SQLite a declared type
    is an affinity that applies to every write: `UPDATE alerts SET ts = 1787897218`
    against a TEXT column stores the *string* "1787897218". The row still answers
    typeof(ts) = 'text', so a loop that converts what is left to convert reads it
    again, fails to parse a bare number as a date, and deletes it. Converted 1220,
    dropped 1220 - the same rows, twice.

    So the table is rebuilt rather than updated: the new one is created from
    SCHEMA, which declares ts INTEGER, and the rows are copied through Python
    because SQLite cannot parse an offset written without a colon.

    All or nothing, in one transaction. SQLite types values, not columns, and an
    integer sorts before every string - a half-converted table would drop
    everything older than the upgrade off the end of every window, silently.
    """
    if conn.execute(
            "SELECT 1 FROM alerts WHERE typeof(ts) = 'text' LIMIT 1").fetchone() is None:
        return

    log.info("Converting stored timestamps to Unix seconds")
    columns = [row["name"] for row in conn.execute("PRAGMA table_info(alerts)")
               if row["name"] != "id"]
    stale = [row["name"] for row in conn.execute(
        "SELECT name FROM sqlite_master WHERE type = 'index' AND tbl_name = 'alerts'")
        if row["name"]]

    conn.execute("ALTER TABLE alerts RENAME TO alerts_iso_ts")
    # The indexes followed the table under their own names, and SCHEMA is about
    # to ask for those names again.
    for name in stale:
        conn.execute(f"DROP INDEX IF EXISTS {name}")
    conn.executescript(SCHEMA)

    placeholders = ", ".join("?" for _ in columns)
    names = ", ".join(columns)
    converted = dropped = 0
    while True:
        batch = conn.execute(
            f"SELECT id, {names} FROM alerts_iso_ts LIMIT 5000").fetchall()
        if not batch:
            break
        done = []
        for row in batch:
            done.append(row["id"])
            when = _parse_iso(row["ts"])
            if when is None:
                # Unreadable rather than merely old. Carried over it would be a
                # string in an integer column, which is the fault this fixes.
                dropped += 1
                continue
            values = [when if name == "ts" else row[name] for name in columns]
            conn.execute(f"INSERT INTO alerts ({names}) VALUES ({placeholders})", values)
            converted += 1
        conn.execute(
            "DELETE FROM alerts_iso_ts WHERE id IN (%s)" % ", ".join("?" for _ in done),
            done)

    conn.execute("DROP TABLE alerts_iso_ts")
    log.info("Converted %d timestamps%s", converted,
             f", dropped {dropped} unreadable" if dropped else "")


def _parse_iso(value: Any) -> int | None:
    """One stored timestamp as Unix seconds, or None if it is not one."""
    if isinstance(value, int):
        return value
    try:
        when = datetime.fromisoformat(value)
    except (TypeError, ValueError):
        return None
    if when.tzinfo is None:
        when = when.astimezone()
    return int(when.timestamp())


def _drop_stored_duplicate_anomalies(conn: sqlite3.Connection) -> None:
    """Remove anomaly rows the engine's own event rule had already reported.

    The same pairing without_duplicate_anomalies() now refuses at the door,
    applied once to what is already on disk. Rows written before that check
    existed doubled every count they touched, and leaving them would mean the
    dashboard kept disagreeing with itself across the retention window.

    Deletes only where an engine event rule fired on the same packet, so an
    anomaly nothing else reported survives. An event with no flow of its own is
    safe without a guard of its own: json_extract returns NULL for it, and NULL
    never equals NULL, so the pairing below simply cannot match.

    Idempotent, and a no-op on a database that never held a duplicate.
    """
    removed = conn.execute(
        """DELETE FROM alerts
            WHERE event_type = 'anomaly'
              AND EXISTS (
                    SELECT 1 FROM alerts twin
                     WHERE twin.event_type = 'alert'
                       AND twin.ts = alerts.ts
                       AND twin.signature_id BETWEEN ? AND ?
                       AND json_extract(twin.raw, '$.timestamp')
                           = json_extract(alerts.raw, '$.timestamp')
                       AND json_extract(twin.raw, '$.flow_id')
                           = json_extract(alerts.raw, '$.flow_id'))""",
        (ENGINE_EVENT_SID_MIN, ENGINE_EVENT_SID_MAX),
    ).rowcount
    if removed:
        log.info("Removed %d anomaly rows an alert already described", removed)


def _label_unnamed(conn: sqlite3.Connection) -> None:
    """Give a name to rows stored before non-alert events got one.

    Anomalies carry no signature, so they used to land with an empty one and the
    panel showed them as "(unnamed)" - which reads as a fault in the panel rather
    than as a report from the engine. New rows are labelled as they arrive; these
    are the ones already on disk.
    """
    from .modules.suricata.tailer import _label_for  # circular at module level

    rows = conn.execute(
        "SELECT id, raw FROM alerts WHERE signature IS NULL OR signature = ''"
    ).fetchall()
    for row in rows:
        try:
            label = _label_for(json.loads(row["raw"]))
        except (ValueError, TypeError):
            continue
        if label:
            conn.execute("UPDATE alerts SET signature = ? WHERE id = ?", (label, row["id"]))
    if rows:
        log.info("Labelled %d stored events that had no signature", len(rows))



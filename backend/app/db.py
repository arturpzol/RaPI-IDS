# Suricata's own event rules - the ones it ships in app-layer-events.rules and
# its siblings, rather than anything Emerging Threats wrote. Every SID in this
# range exists to raise an alert for a condition the engine also writes to the
# anomaly log, which is exactly why a row from one is the twin of a row from the
# other. An ET rule that happens to fire on the same packet is not a twin, and
# the range is what tells the two apart.
ENGINE_EVENT_SID_MIN = 2200000
ENGINE_EVENT_SID_MAX = 2299999


# The alerts table holds two different things, and the dashboard was counting
# them as one. An engine event rule reports on the traffic or on the engine
# itself; an Emerging Threats rule reports on something somebody did. On this
# sensor that was 1176 rows against 3177 - a quarter of every figure the panel
# drew was not an alert at all, and "unacknowledged only" listed 1171 items
# nobody can acknowledge, because a retransmission is not a piece of work.
#
# COALESCE, not a bare comparison: signature_id is NULL on anomaly records, and
# NULL BETWEEN is NULL, which would put those rows in neither half.
DIAGNOSTIC_SQL = (f"(event_type = 'anomaly' OR COALESCE(signature_id, 0) "
                  f"BETWEEN {ENGINE_EVENT_SID_MIN} AND {ENGINE_EVENT_SID_MAX})")
THREAT_SQL = f"NOT {DIAGNOSTIC_SQL}"

# What every dashboard figure counts. Diagnostics have their own screen.
SUMMARY_SCOPE = THREAT_SQL


def _twin_key(event: dict[str, Any]) -> tuple[str, int] | None:
    """What identifies one detection across the engine's two ways of reporting it.

    The anomaly record and the alert from the engine's own event rule describe
    the same packet, so they carry the same EVE timestamp to the microsecond and
    the same flow_id. Nothing else lines up: the wording differs ("error_on_data"
    against "SURICATA QUIC error on data", "APPLAYER_PROTO_DETECTION_SKIPPED"
    against "Applayer Protocol detection skipped"), and the ts column holds
    seconds, which is far too coarse - a busy flow puts dozens of unrelated
    events inside one second.

    None for an event with no flow of its own. That key would be weak enough to
    collapse unrelated rows, so those are left exactly as they arrived.
    """
    stamp = event.get("timestamp")
    flow = event.get("flow_id")
    if isinstance(stamp, str) and isinstance(flow, int):
        return stamp, flow
    return None


def is_diagnostic(row: dict[str, Any]) -> bool:
    """The same split as DIAGNOSTIC_SQL, for a row that is not in the table yet.

    The queries were scoped and the live path was not, so every diagnostic still
    went out over the WebSocket as an alert and into the mail queue behind it.
    On this sensor that is 16 584 "SURICATA Ethertype unknown" - a decoder note
    with no source, no destination and no protocol, because the frame it is
    about has no IP layer to report.

    Kept beside DIAGNOSTIC_SQL on purpose, and a test runs both over the same
    rows: a predicate in Python and a predicate in SQL that must agree is
    exactly the pair that drifts.
    """
    if row.get("event_type") == "anomaly":
        return True
    sid = row.get("signature_id")
    if sid is None:
        sid = ((row.get("raw") or {}).get("alert") or {}).get("signature_id")
    return isinstance(sid, int) and ENGINE_EVENT_SID_MIN <= sid <= ENGINE_EVENT_SID_MAX


def _is_engine_event_alert(row: dict[str, Any]) -> bool:
    """True for an alert raised by one of Suricata's built-in event rules."""
    if row.get("event_type") != "alert":
        return False
    sid = row.get("signature_id")
    if sid is None:
        sid = ((row.get("raw") or {}).get("alert") or {}).get("signature_id")
    return isinstance(sid, int) and ENGINE_EVENT_SID_MIN <= sid <= ENGINE_EVENT_SID_MAX


def _stored_engine_event(conn: sqlite3.Connection, ts: int,
                         key: tuple[str, int]) -> bool:
    """Is the twin alert already in the table, from an earlier batch?"""
    stamp, flow = key
    return conn.execute(
        """SELECT 1 FROM alerts
            WHERE ts = ? AND event_type = 'alert'
              AND signature_id BETWEEN ? AND ?
              AND json_extract(raw, '$.timestamp') = ?
              AND json_extract(raw, '$.flow_id') = ?
            LIMIT 1""",
        (ts, ENGINE_EVENT_SID_MIN, ENGINE_EVENT_SID_MAX, stamp, flow),
    ).fetchone() is not None


def without_duplicate_anomalies(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Drop the anomaly rows that an engine event rule already reported.

    The engine reports one condition twice: once in the anomaly log, once as an
    alert from the rule written for that condition. Both landed in this table,
    and every figure the panel produces - the tile, the hourly chart, the map,
    the country ranking - counts rows. A 27 minute video call put 1034 rows in
    for 685 detections. Worse than the inflated total: only QUIC-heavy hours
    inflate, so the shape of the day was wrong too, and one ordinary call looked
    like the worst hour of the week.

    The alert is the row kept. It carries app_proto, direction and the flow
    counters; the anomaly record is little more than a header. An anomaly with
    no such alert behind it is kept as it is - INVALID_GAP has no rule to raise
    it, and an anomaly is often the reason an alert that should have fired did
    not.
    """
    twins = set()
    for row in rows:
        if _is_engine_event_alert(row):
            key = _twin_key(row.get("raw") or {})
            if key is not None:
                twins.add(key)

    keep: list[dict[str, Any]] = []
    conn: sqlite3.Connection | None = None
    for row in rows:
        key = (_twin_key(row.get("raw") or {})
               if row.get("event_type") == "anomaly" else None)
        if key is None:
            keep.append(row)
        elif key in twins:
            continue
        else:
            # The engine writes the alert first and the anomaly second, so a
            # batch boundary between the two leaves the alert already stored.
            # Rare, which is why it costs a query only for the anomalies this
            # batch could not account for by itself.
            if conn is None:
                conn = connect()
            if not _stored_engine_event(conn, row["ts"], key):
                keep.append(row)
    return keep


def insert_alerts(rows: Iterable[dict[str, Any]]) -> list[int]:
    """Insert a batch of alerts, return the assigned ids in the same order."""
    rows = list(rows)
    if not rows:
        return []
    conn = connect()
    ids: list[int] = []
    with _write_lock:
        cur = conn.cursor()
        for r in rows:
            cur.execute(
                """INSERT INTO alerts
                   (ts, event_type, src_ip, src_port, dest_ip, dest_port, proto,
                    app_proto, signature, signature_id, category, severity,
                    et_severity, action, iface,
                    src_cc, raw)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                (
                    r["ts"], r["event_type"], r.get("src_ip"), r.get("src_port"),
                    r.get("dest_ip"), r.get("dest_port"), r.get("proto"),
                    r.get("app_proto"), r.get("signature"), r.get("signature_id"),
                    r.get("category"), r.get("severity"),
                    # Taken from the event when the caller did not work it out,
                    # so a row can never end up with a raw event that says one
                    # thing and a column that says another.
                    r.get("et_severity", et_severity_of(r.get("raw") or {})),
                    # Same rule as the rating above: taken from the event when
                    # the caller did not, so the column and the record agree.
                    r.get("action",
                          ((r.get("raw") or {}).get("alert") or {}).get("action")),
                    r.get("iface"), r.get("src_cc"),
                    json.dumps(r["raw"], separators=(",", ":")),
                ),
            )
            ids.append(cur.lastrowid)
        conn.commit()
    return ids


def save_reader_state(path: str, inode: int, offset: int) -> None:
    conn = connect()
    with _write_lock:
        conn.execute(
            """INSERT INTO reader_state (path, inode, offset) VALUES (?,?,?)
               ON CONFLICT(path) DO UPDATE SET inode=excluded.inode, offset=excluded.offset""",
            (path, inode, offset),
        )
        conn.commit()


def load_reader_state(path: str) -> tuple[int, int] | None:
    row = connect().execute(
        "SELECT inode, offset FROM reader_state WHERE path = ?", (path,)
    ).fetchone()
    return (row["inode"], row["offset"]) if row else None



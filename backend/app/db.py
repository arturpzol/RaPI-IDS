def user_count() -> int:
    return connect().execute("SELECT COUNT(*) AS n FROM users").fetchone()["n"]


def create_first_user(username: str, password_hash: str) -> int | None:
    """Claims an unclaimed panel. Returns None if it was already claimed.

    The emptiness check has to be inside the same statement as the insert. Split
    across two - count, then insert - two requests arriving together both see an
    empty table and both succeed, because the UNIQUE constraint is on the
    username and they may pick different ones. That leaves a second owner
    account on a device whose owner believes they just claimed it, and nothing
    on any screen says so. The window is the width of one scrypt, and it is open
    exactly once: on a fresh image sitting on a network the owner does not
    control yet.

    INSERT ... SELECT ... WHERE NOT EXISTS makes the check part of the write, so
    SQLite's own write lock is what serialises it.
    """
    conn = connect()
    with _write_lock:
        cur = conn.execute(
            "INSERT INTO users (username, password_hash, created_at)"
            " SELECT ?, ?, ? WHERE NOT EXISTS (SELECT 1 FROM users)",
            (username, password_hash, datetime.now(timezone.utc).isoformat()),
        )
        conn.commit()
    return int(cur.lastrowid) if cur.rowcount else None



def acknowledge_all(cutoff: int) -> int:
    """Mark everything unacknowledged up to `cutoff` as reviewed. Returns rows.

    The cutoff is what keeps the button honest. Clearing "everything" would
    also clear alerts that arrive while the statement runs, which is exactly
    the alert somebody would then never see. Anything newer than the moment the
    button was pressed stays in the queue.

    Both kinds are cleared, threats and the engine's own notes. The queue on
    screen counts threats only, but leaving the notes marked unread would mean
    the list's "unacknowledged only" filter still had entries in it after the
    operator had just been told the queue was empty.
    """
    conn = connect()
    with _write_lock:
        cur = conn.execute(
            "UPDATE alerts SET acknowledged = 1 WHERE acknowledged = 0 AND ts <= ?",
            (cutoff,),
        )
        conn.commit()
    return cur.rowcount


def set_acknowledged(alert_id: int, value: bool) -> bool:
    conn = connect()
    with _write_lock:
        cur = conn.execute(
            "UPDATE alerts SET acknowledged = ? WHERE id = ?", (1 if value else 0, alert_id)
        )
        conn.commit()
    return cur.rowcount > 0



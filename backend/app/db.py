def _now() -> int:
    """Unix seconds. The one spelling of "the current moment" in this module."""
    return int(datetime.now(timezone.utc).timestamp())


# The two calendar days the dashboard names. The alert list takes one of these
# rather than a pair of timestamps, so the rows it shows are the rows the tile
# counted: same boundaries, worked out in the same place, on the clock the
# engine writes its timestamps with.
DAYS = ("today", "yesterday")


def day_range(day: str) -> tuple[int, int | None]:
    """Seconds a named calendar day covers, open ended for today."""
    yesterday, today = _day_starts(_now())
    if day == "yesterday":
        return yesterday, today
    if day == "today":
        return today, None
    raise ValueError(f"unknown day: {day}")


def _day_starts(now: int) -> tuple[int, int]:
    """Local midnight that opened yesterday and the one that opened today.

    Calendar days, not multiples of 86400, and built through the date rather
    than by subtracting a day's worth of seconds: on the two nights a year the
    clocks move, "24 hours ago" and "yesterday at midnight" are an hour apart,
    and the daily figures would be one hour of alerts out for a day.

    Local, because the person reading the screen is in the same room as the
    device. UTC midnight would move the reset to a time nobody recognises.
    """
    today = datetime.fromtimestamp(now).date()
    start = datetime(today.year, today.month, today.day)
    return int((start - timedelta(days=1)).timestamp()), int(start.timestamp())



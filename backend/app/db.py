def alert_summary(hours: int = 24) -> dict[str, Any]:
    """Dashboard aggregates: counters, top signatures/sources, hourly histogram.

    Threats only. The engine's own event rules are counted separately and
    reported as one number, because mixing them in made a quarter of this
    dashboard describe the health of the link rather than anything anybody did
    - and one video call outranked the week's real alerts. See SUMMARY_SCOPE.
    The count is what the alert list links to: query_alerts(kind="diagnostic")
    lists them in the same table, with the same search and the same time window.

    Within that scope everything stored is counted. What the operator does not
    want to see is not stored in the first place, because the rule that would
    have produced it is not loaded - see protection.set_informational.
    """
    since = _since(hours)
    conn = connect()
    window = [since]

    def rows(sql: str, params: Iterable[Any] = ()) -> list[dict[str, Any]]:
        return [dict(r) for r in conn.execute(sql, list(params)).fetchall()]

    total_all = conn.execute(
        f"SELECT COUNT(*) AS c FROM alerts WHERE {SUMMARY_SCOPE}").fetchone()["c"]
    total_window = conn.execute(
        f"SELECT COUNT(*) AS c FROM alerts WHERE ts >= ? AND {SUMMARY_SCOPE}", window
    ).fetchone()["c"]
    # Reported beside the tile rather than folded into it: out of the count,
    # never out of sight, so the number on screen and the rows in the table
    # still add up for anybody who checks.
    diagnostics = conn.execute(
        f"SELECT COUNT(*) AS c FROM alerts WHERE ts >= ? AND {DIAGNOSTIC_SQL}", window
    ).fetchone()["c"]
    # What the engine actually stopped, as opposed to what matched. Only ever
    # non-zero while it is inline on a queue; on a sensor reading a copy every
    # alert is "allowed" and this stays at zero, which is the honest answer.
    blocked = conn.execute(
        f"SELECT COUNT(*) AS c FROM alerts "
        f"WHERE ts >= ? AND action = 'blocked' AND {SUMMARY_SCOPE}", window
    ).fetchone()["c"]
    # The queue, and the one figure on the dashboard that is not windowed.
    #
    # A window answers "how loud is it now" and has to fall on its own, because
    # its far edge moves with the clock. That is the honest behaviour of a
    # window and it is also why it cannot be the headline: read as "what is
    # waiting for me" it looks like the panel is losing rows overnight.
    #
    # This one only moves when the operator moves it, or when a new alert
    # arrives. It counts the whole table on purpose. The earlier objection to
    # that - acknowledging a month of alerts is not work anyone does - was an
    # argument for acknowledge_all(), not for hiding the backlog.
    pending = conn.execute(
        f"SELECT COUNT(*) AS c FROM alerts WHERE acknowledged = 0 AND {SUMMARY_SCOPE}"
    ).fetchone()["c"]
    # Calendar days, so the number resets at a moment everybody already knows.
    # Yesterday travels with today because a day's count on its own says
    # nothing: 35 is a quiet morning or a dead sensor, and only the day before
    # it tells you which.
    yesterday_start, today_start = _day_starts(_now())
    today = conn.execute(
        f"SELECT COUNT(*) AS c FROM alerts WHERE ts >= ? AND {SUMMARY_SCOPE}",
        [today_start],
    ).fetchone()["c"]
    # The same day and the one before it, split by ET's rating.
    #
    # This is the answer to "how bad is it", and it belongs above the fold. A
    # total says how many, never how serious: 417 alerts is a bad morning or a
    # quiet one depending entirely on whether any of them is Critical, and the
    # rating breakdown used to live in a rank list at the bottom of the page.
    #
    # Counted over calendar days rather than the rolling window for the same
    # reason the totals are: a figure that falls on its own cannot sit at the
    # top of a screen and be trusted.
    def _ratings(lo: int, hi: int | None) -> list[dict[str, Any]]:
        clause = "ts >= ?" if hi is None else "ts >= ? AND ts < ?"
        params = [lo] if hi is None else [lo, hi]
        return rows(
            f"""SELECT et_severity AS severity, COUNT(*) AS count FROM alerts
                WHERE {clause} AND {SUMMARY_SCOPE}
                GROUP BY et_severity ORDER BY {ET_RANK_SQL}""",
            params,
        )

    today_ratings = _ratings(today_start, None)
    yesterday_ratings = _ratings(yesterday_start, today_start)
    # The engine's own notes for the same calendar day. Reported beside today's
    # count and never folded into it: they describe the traffic and the sensor,
    # not anything anybody did, and mixing them in made a quarter of this
    # dashboard read as somebody's video call outranking the week's real
    # alerts. Counted over the same day, so the two numbers printed together
    # belong to the same period.
    diagnostics_today = conn.execute(
        f"SELECT COUNT(*) AS c FROM alerts WHERE ts >= ? AND {DIAGNOSTIC_SQL}",
        [today_start],
    ).fetchone()["c"]
    yesterday = conn.execute(
        f"SELECT COUNT(*) AS c FROM alerts "
        f"WHERE ts >= ? AND ts < ? AND {SUMMARY_SCOPE}",
        [yesterday_start, today_start],
    ).fetchone()["c"]
    # Windowed. It used to count the whole table, which on a tile wired to
    # [alarm] meant a red badge that could never go back to green: acknowledging
    # a month of alerts is not work anyone does.
    unacked = conn.execute(
        f"""SELECT COUNT(*) AS c FROM alerts
            WHERE ts >= ? AND acknowledged = 0 AND {SUMMARY_SCOPE}""",
        window,
    ).fetchone()["c"]

    return {
        "window_hours": hours,
        # Which the timeline below is bucketed by. The label under a point is
        # "07" either way, and it means an hour on one window and a day of the
        # month on the next; the client cannot tell them apart from the data.
        "timeline_step_hours": 24 if hours > HOURLY_TIMELINE_MAX_HOURS else 1,
        "total_all_time": total_all,
        "total_window": total_window,
        "unacknowledged": unacked,
        "pending": pending,
        "today": today,
        "diagnostics_today": diagnostics_today,
        "today_by_severity": today_ratings,
        "yesterday_by_severity": yesterday_ratings,
        "yesterday": yesterday,
        "diagnostics": diagnostics,
        "blocked": blocked,
        "by_severity": rows(
            f"""SELECT et_severity AS severity, COUNT(*) AS count FROM alerts
                WHERE ts >= ? AND {SUMMARY_SCOPE}
                GROUP BY et_severity ORDER BY {ET_RANK_SQL}""",
            window,
        ),
        # Every top-N below carries a second sort column. With only "count DESC"
        # the order among equal counts is whatever the query plan happens to
        # produce, so a list of ten ones - which is most of them on a quiet
        # network - reshuffles when the plan changes and looks like activity.
        "top_signatures": rows(
            f"""SELECT signature, signature_id, et_severity AS severity,
                       COUNT(*) AS count FROM alerts
                WHERE ts >= ? AND {SUMMARY_SCOPE} GROUP BY signature_id, signature
                ORDER BY count DESC, signature_id LIMIT 10""",
            window,
        ),
        "top_sources": rows(
            f"""SELECT src_ip, COUNT(*) AS count FROM alerts
                WHERE ts >= ? AND src_ip IS NOT NULL AND {SUMMARY_SCOPE}
                GROUP BY src_ip ORDER BY count DESC, src_ip LIMIT 10""",
            window,
        ),
        "top_destinations": rows(
            f"""SELECT dest_ip, COUNT(*) AS count FROM alerts
                WHERE ts >= ? AND dest_ip IS NOT NULL AND {SUMMARY_SCOPE}
                GROUP BY dest_ip ORDER BY count DESC, dest_ip LIMIT 10""",
            window,
        ),
        "top_categories": rows(
            f"""SELECT category, COUNT(*) AS count FROM alerts
                WHERE ts >= ? AND category IS NOT NULL AND {SUMMARY_SCOPE}
                GROUP BY category ORDER BY count DESC, category LIMIT 10""",
            window,
        ),
        "timeline": _timeline(conn, since, hours),
    }


def _timeline(conn: sqlite3.Connection, since: int, hours: int) -> list[dict[str, Any]]:
    """Histogram with a severity breakdown, gaps filled with zeros.

    An hour per point up to two days, a day per point beyond that. Thirty days
    of hourly buckets is 720 points, each of them a stack of five bands: it
    renders, and it is not a chart anybody reads. The threshold sits at 48 so
    that "last 24 hours" and a day either side of it keep the hourly shape,
    which is the one that shows when a burst happened.

    The zero fill matters in both: without it the chart draws only the buckets
    that happen to contain alerts, so two spikes a day apart look like constant
    activity.
    """
    if hours > HOURLY_TIMELINE_MAX_HOURS:
        return _timeline_daily(conn, since)
    return _timeline_hourly(conn, since, hours)


def _timeline_daily(conn: sqlite3.Connection, since: int) -> list[dict[str, Any]]:
    """A point per local calendar day.

    Grouped by SQLite's local date rather than by integer division, because a
    day is the one bucket whose length is not fixed: the two nights a year the
    offset moves are 23 and 25 hours long, and dividing epoch seconds by 86400
    would put those days' evenings in the neighbouring bucket. An hour has no
    such problem, which is why the hourly path below still divides.
    """
    rows = conn.execute(
        f"""SELECT date(ts, 'unixepoch', 'localtime') AS bucket,
                   et_severity AS severity, COUNT(*) AS count
            FROM alerts WHERE ts >= ? AND {SUMMARY_SCOPE}
            GROUP BY bucket, et_severity""",
        (since,),
    ).fetchall()

    by_bucket: dict[str, dict[str, int]] = {}
    for row in rows:
        slot = by_bucket.setdefault(row["bucket"], {})
        slot[row["severity"] or ""] = row["count"]

    # Every calendar day the window touches, which for a rolling seven days
    # part-way through today is eight of them. The oldest bar is then a
    # part-day, and it is drawn short rather than dropped: the cutoff is the one
    # the tile above the chart counts from, so a bar missing here would be
    # alerts the tile includes and the chart does not.
    first = datetime.fromtimestamp(since).astimezone().date()
    today = datetime.fromtimestamp(_now()).astimezone().date()
    out: list[dict[str, Any]] = []
    for step in range((today - first).days, -1, -1):
        key = (today - timedelta(days=step)).isoformat()
        severities = by_bucket.get(key, {})
        out.append({
            "bucket": key,
            "count": sum(severities.values()),
            "by_severity": severities,
        })
    return out


def _timeline_hourly(conn: sqlite3.Connection, since: int, hours: int) -> list[dict[str, Any]]:
    """A point per hour.

    Bucketing is integer division, and the generated range is the same division
    over the same seconds - so the two cannot drift apart. Cutting the timestamp
    string at thirteen characters did the same job while the offset held still,
    and put an hour in two buckets on the night it changed.
    """
    rows = conn.execute(
        f"""SELECT ts / 3600 AS bucket, et_severity AS severity, COUNT(*) AS count
            FROM alerts WHERE ts >= ? AND {SUMMARY_SCOPE}
            GROUP BY bucket, et_severity""",
        (since,),
    ).fetchall()

    by_bucket: dict[int, dict[str, int]] = {}
    for row in rows:
        slot = by_bucket.setdefault(row["bucket"], {})
        # "" is the key for a rule with no ET rating, which the chart draws as
        # its own band rather than folding into one of ET's.
        slot[row["severity"] or ""] = row["count"]

    latest = _now() // 3600
    out: list[dict[str, Any]] = []
    for step in range(hours - 1, -1, -1):
        hour = latest - step
        severities = by_bucket.get(hour, {})
        out.append({
            # The label is local wall clock, because that is what somebody
            # reading a chart of their own evening expects to see.
            "bucket": datetime.fromtimestamp(hour * 3600).astimezone().strftime("%Y-%m-%dT%H:00"),
            "count": sum(severities.values()),
            "by_severity": severities,
        })
    return out


def geo_summary(hours: int = 24) -> list[dict[str, Any]]:
    """Alerts grouped by the country of the source address.

    A country is coloured by the worst rating seen from it, which is MIN over
    ET_RANK_SQL because that ranking puts the most serious first. The rank is
    turned back into a label here: it exists to sort, and nothing outside this
    module should have to know the numbers.
    """
    since = _since(hours)
    rows = connect().execute(
        f"""SELECT src_cc                AS code,
                   COUNT(*)              AS count,
                   COUNT(DISTINCT src_ip) AS sources,
                   MIN({ET_RANK_SQL})    AS rank,
                   MAX(ts)               AS last_seen
            FROM alerts
            WHERE ts >= ? AND src_cc IS NOT NULL AND {SUMMARY_SCOPE}
            GROUP BY src_cc
            ORDER BY count DESC""",
        (since,),
    ).fetchall()
    out = []
    for row in rows:
        entry = dict(row)
        rank = entry.pop("rank")
        entry["severity"] = (
            ET_SEVERITIES[rank - 1] if 1 <= rank <= len(ET_SEVERITIES) else None
        )
        out.append(entry)
    return out


def backfill_et_severity(batch: int = 2000) -> int:
    """Fill et_severity on alerts stored before the column existed.

    The label was always there - it rides along in the raw event - so no history
    is lost by having added the column late. Batched with a commit each, for the
    same reason as the country backfill below.
    """
    conn = connect()
    filled = 0
    while True:
        rows = conn.execute(
            "SELECT id, raw FROM alerts WHERE et_severity IS NULL LIMIT ?", (batch,)
        ).fetchall()
        if not rows:
            return filled
        updates = []
        for row in rows:
            try:
                label = et_severity_of(json.loads(row["raw"]))
            except (ValueError, TypeError):
                label = None
            # Rows with no ET rating stay NULL and would be picked up again on
            # the next pass, so they are marked as looked at instead.
            updates.append((label or "", row["id"]))
        with _write_lock:
            conn.executemany("UPDATE alerts SET et_severity = ? WHERE id = ?", updates)
            conn.commit()
        filled += len(updates)


def backfill_actions(batch: int = 2000) -> int:
    """Fill `action` on alerts stored before the column existed.

    The verdict rides along in every stored event, so no history is lost by
    having read it late. Left NULL, "what did this device block" would be a
    question about when the panel was upgraded rather than about the device.

    One statement rather than a Python loop: json_extract is SQLite's own, the
    rows never come into the process, and there is nothing to decide per row.
    Batched all the same, so a database holding weeks of history does not take
    the write lock for the length of one pass.
    """
    conn = connect()
    filled = 0
    while True:
        with _write_lock:
            cur = conn.execute(
                """UPDATE alerts SET action = json_extract(raw, '$.alert.action')
                   WHERE id IN (
                     SELECT id FROM alerts
                      WHERE action IS NULL
                        AND json_extract(raw, '$.alert.action') IS NOT NULL
                      LIMIT ?)""", (batch,))
            conn.commit()
        if not cur.rowcount:
            return filled
        filled += cur.rowcount


def backfill_countries(resolve: Callable[[str], str], batch: int = 2000) -> int:
    """Fill src_cc on alerts stored before the column existed.

    Takes the resolver as an argument so this module keeps knowing nothing about
    geolocation. Runs in batches with a commit each, because on a database with
    weeks of history one transaction would hold the write lock long enough for
    the tailer to start timing out.
    """
    conn = connect()
    filled = 0
    while True:
        rows = conn.execute(
            """SELECT id, src_ip FROM alerts
               WHERE src_cc IS NULL AND src_ip IS NOT NULL LIMIT ?""",
            (batch,),
        ).fetchall()
        if not rows:
            return filled
        updates = [(resolve(row["src_ip"]), row["id"]) for row in rows]
        with _write_lock:
            conn.executemany("UPDATE alerts SET src_cc = ? WHERE id = ?", updates)
            conn.commit()
        filled += len(updates)



def insert_load_samples(rows: list[tuple[int, float, float, float | None, float]]) -> None:
    """Write a batch of minute samples.

    REPLACE rather than INSERT: a clock adjustment can land two samples on the
    same second, and losing one of those matters less than a failed write
    taking the whole batch with it.
    """
    if not rows:
        return
    conn = connect()
    with _write_lock:
        conn.executemany(
            "INSERT OR REPLACE INTO load_samples (ts, cpu, cpu_peak, temp, memory)"
            " VALUES (?,?,?,?,?)",
            rows,
        )
        conn.commit()


def load_samples_since(ts: int) -> list[dict[str, Any]]:
    return [dict(row) for row in connect().execute(
        "SELECT ts, cpu, cpu_peak, temp, memory FROM load_samples"
        " WHERE ts >= ? ORDER BY ts", (ts,),
    )]


def rollup_load_hours(since: int, before: int) -> int:
    """Fold finished hours of minute samples into hourly averages.

    Bounded by `since` so this stays a few hundred rows an hour rather than a
    scan of the whole week. Idempotent - re-running over an hour recomputes the
    same numbers, which is what makes it safe to run after a crash.
    """
    if before <= since:
        return 0
    conn = connect()
    with _write_lock:
        cur = conn.execute(
            """INSERT INTO load_hourly (hour, cpu, cpu_peak, temp, temp_peak, memory, samples)
               SELECT (ts / 3600) * 3600,
                      ROUND(AVG(cpu), 1), ROUND(MAX(cpu_peak), 1),
                      ROUND(AVG(temp), 1), ROUND(MAX(temp), 1),
                      ROUND(AVG(memory), 1), COUNT(*)
                 FROM load_samples
                WHERE ts >= ? AND ts < ?
                GROUP BY ts / 3600
               ON CONFLICT(hour) DO UPDATE SET
                      cpu = excluded.cpu, cpu_peak = excluded.cpu_peak,
                      temp = excluded.temp, temp_peak = excluded.temp_peak,
                      memory = excluded.memory, samples = excluded.samples""",
            (since, before),
        )
        conn.commit()
    return cur.rowcount


